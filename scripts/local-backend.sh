#!/usr/bin/env bash
# ToGo local backend — one command to run a REAL Supabase stack (Postgres + Auth +
# PostgREST + Realtime + Studio) on your machine, apply all migrations, seed demo
# data, and write the client .env files so the web and mobile apps run in CONNECTED
# mode against it. No hosted project required.
#
# Usage:
#   scripts/local-backend.sh up       # start stack, apply migrations + seed, write env
#   scripts/local-backend.sh reset    # re-apply migrations + seed (fresh data), write env
#   scripts/local-backend.sh env      # (re)write .env files from the running stack
#   scripts/local-backend.sh status   # show stack status + URLs/keys
#   scripts/local-backend.sh down     # stop the stack (data is kept)
#   scripts/local-backend.sh down --no-backup   # stop and discard local data
#
# Requirements: Docker (running) and the Supabase CLI. The script preflights both and
# tells you exactly what to install if either is missing.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

# Resolve a Supabase CLI invocation: a global `supabase`, else `npx --yes supabase`.
if command -v supabase >/dev/null 2>&1; then
  SUPABASE=(supabase)
else
  SUPABASE=(npx --yes supabase)
fi

say()  { printf '\033[0;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[0;33m!  \033[0m %s\n' "$*" >&2; }
die()  { printf '\033[0;31mx  \033[0m %s\n' "$*" >&2; exit 1; }

preflight() {
  if ! command -v docker >/dev/null 2>&1; then
    die "Docker is not installed. Install Docker Desktop (https://docs.docker.com/get-docker/), then re-run."
  fi
  if ! docker info >/dev/null 2>&1; then
    die "Docker is installed but the daemon is not running. Start Docker Desktop, then re-run."
  fi
  if ! command -v supabase >/dev/null 2>&1 && ! command -v npx >/dev/null 2>&1; then
    die "Neither the Supabase CLI nor npx is available. Install the CLI (https://supabase.com/docs/guides/cli) or Node.js."
  fi
}

# Write the web .env.local and mobile .env from the running stack's status, so the
# apps connect to THIS local backend. Only the public URL + anon key are written.
write_env() {
  say "Reading local stack status…"
  local status api_url anon_key
  if ! status="$("${SUPABASE[@]}" status -o env 2>/dev/null)"; then
    die "Could not read 'supabase status'. Is the stack up? Run: scripts/local-backend.sh up"
  fi
  api_url="$(printf '%s\n' "$status" | sed -n 's/^API_URL="\{0,1\}\([^"]*\)"\{0,1\}$/\1/p')"
  anon_key="$(printf '%s\n' "$status" | sed -n 's/^ANON_KEY="\{0,1\}\([^"]*\)"\{0,1\}$/\1/p')"
  [ -n "$api_url" ] || die "Could not parse API_URL from supabase status."
  [ -n "$anon_key" ] || die "Could not parse ANON_KEY from supabase status."

  cat > "$ROOT/.env.local" <<EOF
# Auto-generated by scripts/local-backend.sh — points the WEB app at your local
# Supabase stack (connected mode). Safe to commit? No — this file is gitignored.
VITE_SUPABASE_URL=$api_url
VITE_SUPABASE_ANON_KEY=$anon_key
EOF
  say "Wrote .env.local (web → $api_url)"

  cat > "$ROOT/apps/mobile/.env" <<EOF
# Auto-generated by scripts/local-backend.sh — points the MOBILE app at your local
# Supabase stack (connected mode). This file is gitignored.
#
# NOTE: a phone/emulator cannot reach "localhost" on your computer. For a device,
# replace 127.0.0.1 with your computer's LAN IP (e.g. http://192.168.1.20:54321).
EXPO_PUBLIC_SUPABASE_URL=$api_url
EXPO_PUBLIC_SUPABASE_ANON_KEY=$anon_key
EOF
  say "Wrote apps/mobile/.env (mobile → $api_url)"
}

cmd="${1:-up}"
case "$cmd" in
  up)
    preflight
    say "Starting the local Supabase stack (first run pulls Docker images)…"
    "${SUPABASE[@]}" start
    say "Applying migrations + seed (supabase db reset)…"
    "${SUPABASE[@]}" db reset
    write_env
    say "Done. Local backend is up."
    echo
    echo "  Studio:   http://127.0.0.1:54323"
    echo "  Mailbox:  http://127.0.0.1:54324  (sign-up/reset emails land here)"
    echo
    echo "  Next: run the web app in connected mode against it:"
    echo "    npm run dev          # http://localhost:5173  (reads .env.local)"
    echo
    echo "  Make yourself staff/admin: see docs/LOCAL_BACKEND.md (sign up first, then grant)."
    ;;
  reset)
    preflight
    say "Re-applying migrations + seed…"
    "${SUPABASE[@]}" db reset
    write_env
    say "Local data reset to seed."
    ;;
  env)
    write_env
    ;;
  status)
    "${SUPABASE[@]}" status
    ;;
  down)
    if [ "${2:-}" = "--no-backup" ]; then
      "${SUPABASE[@]}" stop --no-backup
    else
      "${SUPABASE[@]}" stop
    fi
    say "Local stack stopped."
    ;;
  *)
    die "Unknown command '$cmd'. Use: up | reset | env | status | down"
    ;;
esac
